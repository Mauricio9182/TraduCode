def classify_word(word):
    w = word.lower().strip(".,!?;:\"'()")
    if w in punctuation:
        return "PUNTUACION"
    if w in contractions:
        return "CONTRACCION"
    if w in articles:
        return "ARTICULO"
    if w in pronouns:
        return "PRONOMBRE"
    if w in conjunctions:
        return "CONJUNCION"
    if w in prepositions:
        return "PREPOSICION"
    if w in adverbs:
        return "ADVERBIO"
    if w in interjections:
        return "INTERJECCION"
    if w in verbs:
        return "VERBO"
    if w in adjectives:
        return "ADJETIVO"
    if w in nouns:
        return "SUSTANTIVO"
